/*
МЕТОД: reduce()
ЩО РОБИТЬ: Бере масив і "згортає" (редукує) його до одного єдиного значення (наприклад, рахує загальну суму всіх елементів).
ГОЛОВНА ФІШКА: Стрілочна функція всередині reduce приймає ДВА обов'язкові параметри:
1. acc (accumulator / акумулятор) - це "коробка", яка запам'ятовує проміжний результат після кожного кроку.
2. item (поточний елемент) - елемент масиву, який ми зараз обробляємо.
Також після самої функції дуже важливо передати стартове значення для акумулятора (зазвичай це 0).
*/

// Ціни на процесор, відеокарту, материнку та оперативку
const pcPartsPrices = [9500, 14000, 5000, 3500]; 

// acc починається з 0. На кожному кроці ми додаємо до нього поточну ціну (price)
const totalCost = pcPartsPrices.reduce((acc, price) => acc + price, 0);

console.log(totalCost);